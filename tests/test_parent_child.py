def test_chroma_vector_store_parent_crud(tmp_path):
    """24. ChromaVectorStore persists, retrieves, counts, and deletes parent records."""
    from app.vectorstore.chroma_store import ChromaVectorStore

    store = ChromaVectorStore(
        persist_dir=tmp_path / "chroma_test",
        collection_name="test_parent_collection",
        expected_dimension=4,
    )
    p1 = ParentChunk(
        parent_id="p_1",
        text="Parent text one",
        source="doc1.pdf",
        page_number=1,
        parent_index=0,
        document_id="doc1",
    )
    p2 = ParentChunk(
        parent_id="p_2",
        text="Parent text two",
        source="doc2.pdf",
        page_number=1,
        parent_index=0,
        document_id="doc2",
    )

    added = store.add_parents([p1, p2])
    assert added == 2
    assert store.count_parents() == 2

    # Fetch
    fetched = store.get_parents(["p_1", "p_2"])
    assert "p_1" in fetched and "p_2" in fetched
    assert fetched["p_1"]["text"] == "Parent text one"
    assert fetched["p_1"]["document_id"] == "doc1"

    # Delete by document_id
    store.delete_by_document_id("doc1")
    assert store.count_parents() == 1
    assert store.get_parent("p_1") is None
    assert store.get_parent("p_2") is not None

    # Reset
    store.reset()
    assert store.count_parents() == 0


