def test_duplicate_parent_elimination():
    """7. Multiple child chunks belonging to the same parent are merged into a single parent context."""
    parent_store = {
        "parent_1": {
            "parent_id": "parent_1",
            "text": "Full parent section 1 text spanning both child A and B.",
            "source": "doc1.pdf",
            "page_number": 1,
            "document_id": "doc1",
        },
        "parent_2": {
            "parent_id": "parent_2",
            "text": "Full parent section 2 text for child C.",
            "source": "doc1.pdf",
            "page_number": 2,
            "document_id": "doc1",
        },
    }

    # Child A and Child B both point to parent_1; Child C points to parent_2
    child_a = RetrievedChunk(
        chunk_id="c_a",
        text="child text a",
        source="doc1.pdf",
        page_number=1,
        chunk_index=0,
        distance=0.20,
        parent_id="parent_1",
    )
    child_b = RetrievedChunk(
        chunk_id="c_b",
        text="child text b",
        source="doc1.pdf",
        page_number=1,
        chunk_index=1,
        distance=0.35,
        parent_id="parent_1",
    )
    child_c = RetrievedChunk(
        chunk_id="c_c",
        text="child text c",
        source="doc1.pdf",
        page_number=2,
        chunk_index=0,
        distance=0.15,
        parent_id="parent_2",
    )

    resolved = resolve_parent_context([child_a, child_b, child_c], parent_store=parent_store)
    # 3 children must collapse into exactly 2 parent contexts
    assert len(resolved) == 2
    assert resolved[0].chunk_id == "parent_1"
    assert resolved[1].chunk_id == "parent_2"
    assert resolved[0].text == "Full parent section 1 text spanning both child A and B."
    assert resolved[1].text == "Full parent section 2 text for child C."


